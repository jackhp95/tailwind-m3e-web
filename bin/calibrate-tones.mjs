#!/usr/bin/env node
/*
 * bin/calibrate-tones.mjs
 *
 * Pipeline A — calibrates M3 tone → OKLCH lightness for two chroma profiles
 * (rich = primary/secondary/tertiary/error palettes; neutral = neutral/
 * neutral-variant palettes). Samples MCU's TonalPalette across 12 hues
 * × 12 tones, converts each generated hex to OKLCH L, averages over hues.
 *
 * Output: src/ref/_tone-table.css (deterministic, checked in).
 *
 * Re-run manually only when bumping @material/material-color-utilities
 * or revisiting the approximation.
 */
import { TonalPalette, hexFromArgb } from "@material/material-color-utilities";
import { converter, parse } from "culori";
import { writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = join(__dirname, "..", "src", "ref", "_tone-table.css");

const TONES = [10, 20, 30, 40, 50, 60, 70, 80, 90, 95, 99, 100];
const HUES = [0, 30, 60, 90, 120, 150, 180, 210, 240, 270, 300, 330];

// M3 chroma constants per spec (matraic's m3e + MCU defaults):
//   primary/secondary/tertiary use chroma ≥ 32 — call this "rich"
//   neutral uses chroma 4; neutral-variant uses chroma 8 — average as "neutral"
const CHROMA_RICH = 40;
const CHROMA_NEUTRAL = 6; // midpoint of 4 and 8

const toOklch = converter("oklch");

function lForToneAtHue(hue, chroma, tone) {
  const palette = TonalPalette.fromHueAndChroma(hue, chroma);
  const argb = palette.tone(tone);
  const hex = hexFromArgb(argb);
  const oklch = toOklch(parse(hex));
  return oklch.l * 100; // culori returns L in [0,1]; we want percent
}

function averageLPerTone(chroma) {
  const out = {};
  for (const tone of TONES) {
    let sum = 0;
    for (const hue of HUES) {
      sum += lForToneAtHue(hue, chroma, tone);
    }
    out[tone] = +(sum / HUES.length).toFixed(2);
  }
  return out;
}

export function calibrate() {
  return {
    rich: averageLPerTone(CHROMA_RICH),
    neutral: averageLPerTone(CHROMA_NEUTRAL),
  };
}

export function emitCss({ rich, neutral }) {
  const lines = [];
  lines.push("/*");
  lines.push(" * AUTOGENERATED — DO NOT EDIT");
  lines.push(" *");
  lines.push(" * Generated by bin/calibrate-tones.mjs by sampling");
  lines.push(" * @material/material-color-utilities's HCT output across 12 hues × 12 tones,");
  lines.push(" * averaging the OKLCH L value per tone. One profile per chroma bucket.");
  lines.push(" *");
  lines.push(" * Consumed by src/ref/palette.css.");
  lines.push(" */");
  lines.push("");
  lines.push(":where(:root) {");
  lines.push("  /* Chroma-rich profile — primary/secondary/tertiary/error tonal palettes. */");
  for (const tone of TONES) {
    lines.push(`  --_m3e-tone-${tone}-rich: ${rich[tone]}%;`);
  }
  lines.push("");
  lines.push("  /* Neutral profile — neutral and neutral-variant tonal palettes. */");
  for (const tone of TONES) {
    lines.push(`  --_m3e-tone-${tone}-neutral: ${neutral[tone]}%;`);
  }
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

export async function main() {
  const table = calibrate();
  await mkdir(dirname(OUT_PATH), { recursive: true });
  await writeFile(OUT_PATH, emitCss(table));
  console.log(`Wrote ${TONES.length * 2} tone L values → ${OUT_PATH}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
